-- Esquema de saldos de fotocopias por maestro. Ejecutar en Supabase SQL Editor.
-- RLS limita los directores a lectura de los datos de su escuela.
create extension if not exists pgcrypto;

create table if not exists public.escuelas (
  id bigint generated by default as identity primary key,
  nombre text not null,
  codigo text unique,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);
create table if not exists public.perfiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null,
  rol text not null check (rol in ('admin','director')),
  escuela_id bigint references public.escuelas(id),
  creado_en timestamptz not null default now(),
  constraint director_requiere_escuela check (rol <> 'director' or escuela_id is not null)
);
create table if not exists public.maestros (
  id bigint generated by default as identity primary key,
  nombre text not null,
  escuela_id bigint not null references public.escuelas(id),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  unique(id, escuela_id)
);
create table if not exists public.cheques (
  id bigint generated by default as identity primary key,
  escuela_id bigint not null references public.escuelas(id),
  numero text not null,
  banco text not null,
  monto numeric(12,2) not null check (monto > 0),
  fecha date not null,
  anulado boolean not null default false,
  motivo_anulacion text,
  creado_por uuid references public.perfiles(id),
  creado_en timestamptz not null default now(),
  unique(escuela_id, numero)
);
create table if not exists public.asignaciones (
  id bigint generated by default as identity primary key,
  cheque_id bigint not null references public.cheques(id),
  maestro_id bigint not null references public.maestros(id),
  escuela_id bigint not null references public.escuelas(id),
  mes date not null,
  monto numeric(12,2) not null check(monto > 0),
  observacion text,
  anulado boolean not null default false,
  motivo_anulacion text,
  creado_por uuid references public.perfiles(id),
  creado_en timestamptz not null default now(),
  constraint asignacion_mes_inicio check (extract(day from mes)=1),
  constraint asignacion_maestro_escuela foreign key(maestro_id,escuela_id) references public.maestros(id,escuela_id)
);
create table if not exists public.consumos (
  id bigint generated by default as identity primary key,
  maestro_id bigint not null references public.maestros(id),
  fecha date not null,
  responsable text not null,
  descripcion text not null,
  monto numeric(12,2) not null check(monto > 0),
  recibido boolean not null default false,
  recibido_nombre text,
  anulado boolean not null default false,
  motivo_anulacion text,
  creado_por uuid references public.perfiles(id),
  creado_en timestamptz not null default now()
);
create index if not exists maestros_escuela_idx on public.maestros(escuela_id);
create index if not exists asignaciones_maestro_mes_idx on public.asignaciones(maestro_id,mes);
create index if not exists consumos_maestro_fecha_idx on public.consumos(maestro_id,fecha);

create or replace function public.mi_rol() returns text language sql stable security definer set search_path=public as $$ select rol from public.perfiles where id=auth.uid() $$;
create or replace function public.mi_escuela() returns bigint language sql stable security definer set search_path=public as $$ select escuela_id from public.perfiles where id=auth.uid() $$;
create or replace function public.es_admin() returns boolean language sql stable security definer set search_path=public as $$ select coalesce(public.mi_rol()='admin',false) $$;
revoke all on function public.mi_rol(),public.mi_escuela(),public.es_admin() from public;
grant execute on function public.mi_rol(),public.mi_escuela(),public.es_admin() to authenticated;

alter table public.perfiles enable row level security;
alter table public.escuelas enable row level security;
alter table public.maestros enable row level security;
alter table public.cheques enable row level security;
alter table public.asignaciones enable row level security;
alter table public.consumos enable row level security;
drop policy if exists perfil_lectura_propia on public.perfiles;
create policy perfil_lectura_propia on public.perfiles for select to authenticated using(id=auth.uid() or public.es_admin());
drop policy if exists perfiles_admin on public.perfiles;
create policy perfiles_admin on public.perfiles for all to authenticated using(public.es_admin()) with check(public.es_admin());
drop policy if exists escuelas_select on public.escuelas;
create policy escuelas_select on public.escuelas for select to authenticated using(public.es_admin() or id=public.mi_escuela());
drop policy if exists escuelas_admin on public.escuelas;
create policy escuelas_admin on public.escuelas for all to authenticated using(public.es_admin()) with check(public.es_admin());
drop policy if exists maestros_select on public.maestros;
create policy maestros_select on public.maestros for select to authenticated using(public.es_admin() or escuela_id=public.mi_escuela());
drop policy if exists maestros_admin on public.maestros;
create policy maestros_admin on public.maestros for all to authenticated using(public.es_admin()) with check(public.es_admin());
drop policy if exists cheques_admin on public.cheques;
create policy cheques_admin on public.cheques for all to authenticated using(public.es_admin()) with check(public.es_admin());
drop policy if exists asignaciones_select on public.asignaciones;
create policy asignaciones_select on public.asignaciones for select to authenticated using(public.es_admin() or escuela_id=public.mi_escuela());
drop policy if exists asignaciones_admin on public.asignaciones;
create policy asignaciones_admin on public.asignaciones for all to authenticated using(public.es_admin()) with check(public.es_admin());
drop policy if exists consumos_select on public.consumos;
create policy consumos_select on public.consumos for select to authenticated using(public.es_admin() or exists(select 1 from public.maestros m where m.id=maestro_id and m.escuela_id=public.mi_escuela()));
drop policy if exists consumos_admin on public.consumos;
create policy consumos_admin on public.consumos for all to authenticated using(public.es_admin()) with check(public.es_admin());

create or replace view public.cheques_resumen with (security_invoker=true) as
select c.id as cheque_id,c.numero,c.banco,c.fecha,c.escuela_id,e.nombre as escuela,c.monto,
 coalesce(sum(a.monto) filter(where not a.anulado),0)::numeric(12,2) as asignado,
 (c.monto-coalesce(sum(a.monto) filter(where not a.anulado),0))::numeric(12,2) as disponible
from public.cheques c join public.escuelas e on e.id=c.escuela_id left join public.asignaciones a on a.cheque_id=c.id
where not c.anulado group by c.id,e.nombre;
create or replace view public.saldo_maestro with (security_invoker=true) as
select m.id as maestro_id,m.nombre as maestro,e.nombre as escuela,m.escuela_id,
 coalesce(a.asignado,0)::numeric(12,2) as asignado,coalesce(c.consumido,0)::numeric(12,2) as consumido,
 (coalesce(a.asignado,0)-coalesce(c.consumido,0))::numeric(12,2) as saldo
from public.maestros m join public.escuelas e on e.id=m.escuela_id
left join (select maestro_id,sum(monto) asignado from public.asignaciones where not anulado group by maestro_id) a on a.maestro_id=m.id
left join (select maestro_id,sum(monto) consumido from public.consumos where not anulado group by maestro_id) c on c.maestro_id=m.id
where m.activo;
create or replace view public.saldo_mensual with (security_invoker=true) as
select m.id as maestro_id,m.nombre as maestro,e.nombre as escuela,x.mes,
 coalesce(a.asignado,0)::numeric(12,2) as asignado,coalesce(c.consumido,0)::numeric(12,2) as consumido,
 (coalesce(a.asignado,0)-coalesce(c.consumido,0))::numeric(12,2) as saldo
from public.maestros m join public.escuelas e on e.id=m.escuela_id
cross join (select mes from public.asignaciones union select date_trunc('month',fecha)::date from public.consumos) x
left join (select maestro_id,mes,sum(monto) asignado from public.asignaciones where not anulado group by maestro_id,mes) a on a.maestro_id=m.id and a.mes=x.mes
left join (select maestro_id,date_trunc('month',fecha)::date mes,sum(monto) consumido from public.consumos where not anulado group by maestro_id,date_trunc('month',fecha)::date) c on c.maestro_id=m.id and c.mes=x.mes
where (a.maestro_id is not null or c.maestro_id is not null);
create or replace view public.hoja_maestro with (security_invoker=true) as
select c.id as consumo_id,c.maestro_id,c.fecha,c.responsable,c.descripcion,c.monto,c.recibido,c.recibido_nombre,
 (coalesce(a.asignado,0)-sum(c.monto) over(partition by c.maestro_id,date_trunc('month',c.fecha) order by c.fecha,c.id rows unbounded preceding))::numeric(12,2) as saldo
from public.consumos c
left join (select maestro_id,date_trunc('month',mes)::date mes,sum(monto) monto from public.asignaciones where not anulado group by maestro_id,date_trunc('month',mes)) a on a.maestro_id=c.maestro_id and a.mes=date_trunc('month',c.fecha)::date
where not c.anulado;

create or replace function public.registrar_cheque(p_escuela_id bigint,p_numero text,p_banco text,p_monto numeric,p_fecha date)
returns bigint language plpgsql security definer set search_path=public as $$ declare v_id bigint; begin
 if not public.es_admin() then raise exception 'Solo administración puede registrar cheques'; end if;
 insert into public.cheques(escuela_id,numero,banco,monto,fecha,creado_por) values(p_escuela_id,p_numero,p_banco,p_monto,p_fecha,auth.uid()) returning id into v_id; return v_id;
end $$;
create or replace function public.asignar_fondos(p_cheque_id bigint,p_maestro_id bigint,p_mes date,p_monto numeric,p_observacion text default null)
returns bigint language plpgsql security definer set search_path=public as $$ declare v_id bigint; v_escuela bigint; v_disponible numeric; begin
 if not public.es_admin() then raise exception 'Solo administración puede asignar fondos'; end if;
 if p_monto<=0 or extract(day from p_mes)<>1 then raise exception 'Monto o mes inválido'; end if;
 select escuela_id into v_escuela from public.cheques where id=p_cheque_id and not anulado for update;
 if v_escuela is null then raise exception 'Cheque no encontrado o anulado'; end if;
 if not exists(select 1 from public.maestros where id=p_maestro_id and escuela_id=v_escuela) then raise exception 'El maestro debe pertenecer a la escuela del cheque'; end if;
 select monto-coalesce((select sum(monto) from public.asignaciones where cheque_id=p_cheque_id and not anulado),0) into v_disponible from public.cheques where id=p_cheque_id;
 if p_monto>v_disponible then raise exception 'El monto supera lo disponible en el cheque'; end if;
 insert into public.asignaciones(cheque_id,maestro_id,escuela_id,mes,monto,observacion,creado_por) values(p_cheque_id,p_maestro_id,v_escuela,p_mes,p_monto,p_observacion,auth.uid()) returning id into v_id; return v_id;
end $$;
create or replace function public.registrar_consumo(p_maestro_id bigint,p_fecha date,p_responsable text,p_descripcion text,p_monto numeric,p_recibido boolean default false,p_recibido_nombre text default null)
returns bigint language plpgsql security definer set search_path=public as $$ declare v_id bigint; begin
 if not public.es_admin() then raise exception 'Solo administración puede registrar consumos'; end if;
 if p_monto<=0 then raise exception 'El monto debe ser mayor a cero'; end if;
 insert into public.consumos(maestro_id,fecha,responsable,descripcion,monto,recibido,recibido_nombre,creado_por) values(p_maestro_id,p_fecha,p_responsable,p_descripcion,p_monto,p_recibido,p_recibido_nombre,auth.uid()) returning id into v_id; return v_id;
end $$;
create or replace function public.anular_movimiento(p_tipo text,p_id bigint,p_motivo text)
returns void language plpgsql security definer set search_path=public as $$ begin
 if not public.es_admin() then raise exception 'Solo administración puede anular registros'; end if;
 if nullif(trim(p_motivo),'') is null then raise exception 'El motivo es obligatorio'; end if;
 if p_tipo='consumo' then update public.consumos set anulado=true,motivo_anulacion=trim(p_motivo) where id=p_id and not anulado;
 elsif p_tipo='asignacion' then update public.asignaciones set anulado=true,motivo_anulacion=trim(p_motivo) where id=p_id and not anulado;
 elsif p_tipo='cheque' then update public.cheques set anulado=true,motivo_anulacion=trim(p_motivo) where id=p_id and not anulado;
 else raise exception 'Tipo de movimiento inválido'; end if;
end $$;
revoke all on function public.registrar_cheque(bigint,text,text,numeric,date),public.asignar_fondos(bigint,bigint,date,numeric,text),public.registrar_consumo(bigint,date,text,text,numeric,boolean,text),public.anular_movimiento(text,bigint,text) from public;
grant execute on function public.registrar_cheque(bigint,text,text,numeric,date),public.asignar_fondos(bigint,bigint,date,numeric,text),public.registrar_consumo(bigint,date,text,text,numeric,boolean,text),public.anular_movimiento(text,bigint,text) to authenticated;
grant select on public.saldo_maestro,public.saldo_mensual,public.hoja_maestro,public.cheques_resumen to authenticated;
grant select on public.escuelas,public.maestros,public.asignaciones,public.consumos,public.perfiles to authenticated;
grant insert,update,delete on public.escuelas,public.maestros,public.perfiles to authenticated;
grant usage,select on all sequences in schema public to authenticated;
