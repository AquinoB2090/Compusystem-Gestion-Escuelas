-- Clientes individuales: consumos propios y contador sin saldo asignado.
create table if not exists public.clientes_individuales (
  id bigint generated by default as identity primary key,
  nombre text not null,
  telefono text,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

create table if not exists public.consumos_clientes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes_individuales(id) on delete cascade,
  fecha date not null default current_date,
  descripcion text not null,
  cantidad numeric(12,2) not null check (cantidad > 0),
  unidad text not null check (unidad in ('fotocopias', 'quetzales')),
  creado_por uuid references public.perfiles(id),
  creado_en timestamptz not null default now(),
  constraint consumos_clientes_copias_enteras
    check (unidad <> 'fotocopias' or cantidad = trunc(cantidad))
);

create index if not exists consumos_clientes_cliente_fecha_idx
  on public.consumos_clientes(cliente_id, fecha desc);

alter table public.clientes_individuales enable row level security;
alter table public.consumos_clientes enable row level security;
drop policy if exists clientes_individuales_admin on public.clientes_individuales;
create policy clientes_individuales_admin on public.clientes_individuales
  for all to authenticated using (public.es_admin()) with check (public.es_admin());
drop policy if exists consumos_clientes_admin on public.consumos_clientes;
create policy consumos_clientes_admin on public.consumos_clientes
  for all to authenticated using (public.es_admin()) with check (public.es_admin());
grant select, insert, update, delete on public.clientes_individuales, public.consumos_clientes to authenticated;
grant usage, select on sequence public.clientes_individuales_id_seq, public.consumos_clientes_id_seq to authenticated;

