begin;

create table if not exists public.instalaciones_salidas (
  id bigint generated by default as identity primary key,
  lugar text not null check (length(trim(lugar)) > 0),
  fecha_inicio date not null,
  fecha_fin date not null,
  trabajo_realizado text not null check (length(trim(trabajo_realizado)) > 0),
  cobrado numeric(12,2) not null check (cobrado >= 0),
  invertido numeric(12,2) not null check (invertido >= 0),
  ganancia numeric(12,2) generated always as (cobrado - invertido) stored,
  creado_por uuid not null default auth.uid() references auth.users(id),
  creado_en timestamptz not null default now(),
  constraint instalaciones_salidas_fechas_validas check (fecha_fin >= fecha_inicio)
);

alter table public.instalaciones_salidas enable row level security;
drop policy if exists instalaciones_salidas_access on public.instalaciones_salidas;
create policy instalaciones_salidas_access on public.instalaciones_salidas
  for all to authenticated
  using (exists (
    select 1 from public.perfiles p
    where p.id = auth.uid() and p.activo = true and p.rol in ('admin', 'ventas')
  ))
  with check (
    creado_por = auth.uid()
    and exists (
      select 1 from public.perfiles p
      where p.id = auth.uid() and p.activo = true and p.rol in ('admin', 'ventas')
    )
  );

revoke all on public.instalaciones_salidas from public, anon;
grant select, insert on public.instalaciones_salidas to authenticated;
grant usage, select on sequence public.instalaciones_salidas_id_seq to authenticated;

notify pgrst, 'reload schema';
commit;
