-- Catálogos relacionales del taller inspirados en el flujo Cliente → Equipo → Servicio.
begin;
create table if not exists public.taller_clientes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  telefono text not null,
  correo text,
  direccion text,
  creado_en timestamptz not null default now()
);
create table if not exists public.taller_marcas (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  creado_en timestamptz not null default now()
);
create table if not exists public.taller_tecnicos (
  id bigint generated by default as identity primary key,
  nombre text not null,
  telefono text,
  correo text,
  especialidad text,
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);
create table if not exists public.taller_equipos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.taller_clientes(id),
  marca_id bigint references public.taller_marcas(id),
  tipo text not null,
  modelo text not null,
  numero_serie text,
  descripcion text,
  creado_en timestamptz not null default now()
);
alter table public.taller_ordenes
  add column if not exists cliente_id bigint references public.taller_clientes(id),
  add column if not exists equipo_id bigint references public.taller_equipos(id),
  add column if not exists tecnico_id bigint references public.taller_tecnicos(id);
do $$ declare t text; begin
  foreach t in array array['taller_clientes','taller_marcas','taller_tecnicos','taller_equipos'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_access', t);
    execute format('create policy %I on public.%I for all to authenticated using (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in (''admin'',''ventas''))) with check (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in (''admin'',''ventas'')))', t || '_access', t);
  end loop;
end $$;
grant select, insert, update, delete on public.taller_clientes, public.taller_marcas, public.taller_tecnicos, public.taller_equipos to authenticated;
grant usage, select on sequence public.taller_clientes_id_seq, public.taller_marcas_id_seq, public.taller_tecnicos_id_seq, public.taller_equipos_id_seq to authenticated;
notify pgrst, 'reload schema';
commit;
