-- Vincula cuentas de acceso con clientes individuales y permite liquidar sus consumos.
alter table public.perfiles
  add column if not exists cliente_id bigint references public.clientes_individuales(id) on delete cascade;

alter table public.perfiles drop constraint if exists perfiles_rol_check;
alter table public.perfiles
  add constraint perfiles_rol_check check (rol in ('admin', 'director', 'cliente'));

alter table public.perfiles drop constraint if exists perfiles_cliente_requiere_cliente;
alter table public.perfiles
  add constraint perfiles_cliente_requiere_cliente
  check (rol <> 'cliente' or cliente_id is not null);

create unique index if not exists perfiles_cliente_unico_idx
  on public.perfiles(cliente_id) where cliente_id is not null;

create table if not exists public.liquidaciones_clientes (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes_individuales(id) on delete cascade,
  fecha date not null default current_date,
  monto numeric(12,2) not null check (monto > 0),
  descripcion text not null default 'Liquidación',
  creado_por uuid references public.perfiles(id),
  creado_en timestamptz not null default now()
);

create index if not exists liquidaciones_clientes_cliente_fecha_idx
  on public.liquidaciones_clientes(cliente_id, fecha desc);

alter table public.clientes_individuales enable row level security;
alter table public.consumos_clientes enable row level security;
alter table public.liquidaciones_clientes enable row level security;

drop policy if exists clientes_individuales_admin on public.clientes_individuales;
drop policy if exists clientes_individuales_own on public.clientes_individuales;
create policy clientes_individuales_admin on public.clientes_individuales
  for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy clientes_individuales_own on public.clientes_individuales
  for select to authenticated
  using (id = (select p.cliente_id from public.perfiles p where p.id = auth.uid()));

drop policy if exists consumos_clientes_admin on public.consumos_clientes;
drop policy if exists consumos_clientes_own on public.consumos_clientes;
create policy consumos_clientes_admin on public.consumos_clientes
  for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy consumos_clientes_own on public.consumos_clientes
  for select to authenticated
  using (cliente_id = (select p.cliente_id from public.perfiles p where p.id = auth.uid()));

drop policy if exists liquidaciones_clientes_admin on public.liquidaciones_clientes;
drop policy if exists liquidaciones_clientes_own on public.liquidaciones_clientes;
create policy liquidaciones_clientes_admin on public.liquidaciones_clientes
  for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy liquidaciones_clientes_own on public.liquidaciones_clientes
  for select to authenticated
  using (cliente_id = (select p.cliente_id from public.perfiles p where p.id = auth.uid()));

grant select on public.clientes_individuales, public.consumos_clientes, public.liquidaciones_clientes to authenticated;
grant insert, update, delete on public.clientes_individuales, public.consumos_clientes, public.liquidaciones_clientes to authenticated;
grant usage, select on sequence public.liquidaciones_clientes_id_seq to authenticated;

notify pgrst, 'reload schema';
