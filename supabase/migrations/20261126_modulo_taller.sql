-- Taller de reparación. Migración aditiva: conserva toda la información existente.
BEGIN;

create sequence if not exists public.taller_orden_numero_seq;

create table if not exists public.taller_ordenes (
  id bigint generated by default as identity primary key,
  numero bigint not null unique default nextval('public.taller_orden_numero_seq'),
  cliente_nombre text not null,
  cliente_telefono text not null,
  cliente_correo text,
  equipo text not null,
  marca text,
  modelo text,
  serie text,
  accesorios text,
  condicion_recepcion text,
  problema_reportado text not null,
  diagnostico text,
  presupuesto numeric(12,2) check (presupuesto is null or presupuesto >= 0),
  estado text not null default 'recibido' check (estado in ('recibido','diagnostico','esperando_autorizacion','autorizado','reparacion','listo','entregado','no_reparable','cancelado')),
  notas text,
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  entregado_en timestamptz
);
create index if not exists taller_ordenes_estado_creado_idx on public.taller_ordenes(estado, creado_en desc);
create index if not exists taller_ordenes_cliente_idx on public.taller_ordenes using gin(to_tsvector('simple', cliente_nombre || ' ' || equipo || ' ' || problema_reportado));

create table if not exists public.taller_historial (
  id bigint generated by default as identity primary key,
  orden_id bigint not null references public.taller_ordenes(id),
  estado_anterior text,
  estado_nuevo text not null,
  detalle text,
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now()
);
create index if not exists taller_historial_orden_idx on public.taller_historial(orden_id, creado_en desc);

alter table public.taller_ordenes enable row level security;
alter table public.taller_historial enable row level security;
drop policy if exists taller_ordenes_access on public.taller_ordenes;
create policy taller_ordenes_access on public.taller_ordenes for all to authenticated
  using (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in ('admin','ventas')))
  with check (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in ('admin','ventas')));
drop policy if exists taller_historial_access on public.taller_historial;
create policy taller_historial_access on public.taller_historial for all to authenticated
  using (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in ('admin','ventas')))
  with check (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in ('admin','ventas')));
grant select, insert, update on public.taller_ordenes to authenticated;
grant select on public.taller_historial to authenticated;
grant usage, select on sequence public.taller_ordenes_id_seq, public.taller_orden_numero_seq, public.taller_historial_id_seq to authenticated;

create or replace function public.taller_registrar_historial_estado()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.taller_historial(orden_id, estado_nuevo, detalle, creado_por)
    values (new.id, new.estado, 'Equipo recibido en taller.', coalesce(auth.uid(), new.creado_por));
  elsif old.estado is distinct from new.estado then
    if not (case old.estado
      when 'recibido' then new.estado in ('diagnostico','cancelado')
      when 'diagnostico' then new.estado in ('esperando_autorizacion','no_reparable','cancelado')
      when 'esperando_autorizacion' then new.estado in ('autorizado','no_reparable','cancelado')
      when 'autorizado' then new.estado in ('reparacion','cancelado')
      when 'reparacion' then new.estado in ('listo','no_reparable','cancelado')
      when 'listo' then new.estado in ('reparacion','entregado')
      when 'no_reparable' then new.estado in ('entregado','cancelado')
      else false
    end) then
      raise exception 'Cambio de estado no permitido para esta orden.' using errcode = '23514';
    end if;
    if new.estado = 'esperando_autorizacion' and (nullif(btrim(new.diagnostico), '') is null or new.presupuesto is null) then
      raise exception 'Se requiere diagnóstico y presupuesto antes de solicitar autorización.' using errcode = '23514';
    end if;
    insert into public.taller_historial(orden_id, estado_anterior, estado_nuevo, detalle, creado_por)
    values (new.id, old.estado, new.estado, 'Estado actualizado a ' || new.estado || '.', auth.uid());
  end if;
  return new;
end;
$$;
drop trigger if exists taller_ordenes_historial_estado on public.taller_ordenes;
create trigger taller_ordenes_historial_estado
after insert or update of estado on public.taller_ordenes
for each row execute function public.taller_registrar_historial_estado();
revoke all on function public.taller_registrar_historial_estado() from public, anon, authenticated;

notify pgrst, 'reload schema';
COMMIT;
