-- Completa el flujo operativo del taller sin modificar los datos de escuelas.
begin;

alter table public.taller_ordenes
  add column if not exists prioridad text not null default 'normal' check (prioridad in ('baja','normal','alta','urgente')),
  add column if not exists tecnico text,
  add column if not exists autorizado_cliente boolean not null default false,
  add column if not exists autorizado_en timestamptz,
  add column if not exists garantia_dias integer not null default 30 check (garantia_dias >= 0),
  add column if not exists garantia_hasta date,
  add column if not exists trabajo_realizado text;

create table if not exists public.taller_repuestos (
  id bigint generated by default as identity primary key,
  codigo text unique,
  nombre text not null,
  descripcion text,
  costo numeric(12,2) not null default 0 check (costo >= 0),
  precio numeric(12,2) not null default 0 check (precio >= 0),
  existencias integer not null default 0 check (existencias >= 0),
  minimo integer not null default 0 check (minimo >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);
create table if not exists public.taller_orden_repuestos (
  id bigint generated by default as identity primary key,
  orden_id bigint not null references public.taller_ordenes(id) on delete cascade,
  repuesto_id bigint references public.taller_repuestos(id),
  descripcion text not null,
  cantidad integer not null check (cantidad > 0),
  precio_unitario numeric(12,2) not null check (precio_unitario >= 0),
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now()
);
create table if not exists public.taller_pagos (
  id bigint generated by default as identity primary key,
  orden_id bigint not null references public.taller_ordenes(id) on delete cascade,
  monto numeric(12,2) not null check (monto > 0),
  metodo text not null check (metodo in ('efectivo','transferencia','tarjeta','otro')),
  referencia text,
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now()
);
create table if not exists public.taller_comunicaciones (
  id bigint generated by default as identity primary key,
  orden_id bigint not null references public.taller_ordenes(id) on delete cascade,
  canal text not null check (canal in ('llamada','whatsapp','correo','presencial','otro')),
  detalle text not null,
  creado_por uuid references auth.users(id),
  creado_en timestamptz not null default now()
);

create index if not exists taller_pagos_orden_idx on public.taller_pagos(orden_id, creado_en desc);
create index if not exists taller_orden_repuestos_orden_idx on public.taller_orden_repuestos(orden_id);
create index if not exists taller_comunicaciones_orden_idx on public.taller_comunicaciones(orden_id, creado_en desc);

create or replace function public.taller_validar_pago()
returns trigger language plpgsql security definer set search_path=public as $$
declare base numeric(12,2); piezas numeric(12,2); abonado numeric(12,2);
begin
  select presupuesto into base from public.taller_ordenes where id=new.orden_id for update;
  if not found then raise exception 'No se encontró la orden.' using errcode='23503'; end if;
  select coalesce(sum(cantidad*precio_unitario),0) into piezas from public.taller_orden_repuestos where orden_id=new.orden_id;
  select coalesce(sum(monto),0) into abonado from public.taller_pagos where orden_id=new.orden_id;
  if (base is not null or piezas > 0) and new.monto > greatest(0,coalesce(base,0)+piezas-abonado)+0.005 then raise exception 'El pago supera el saldo pendiente de la orden.' using errcode='23514'; end if;
  return new;
end; $$;
drop trigger if exists taller_validar_pago_orden on public.taller_pagos;
create trigger taller_validar_pago_orden before insert on public.taller_pagos
for each row execute function public.taller_validar_pago();
revoke all on function public.taller_validar_pago() from public, anon, authenticated;

create or replace function public.taller_validar_aprobacion_cliente()
returns trigger language plpgsql set search_path=public as $$
begin
  if new.estado='autorizado' and not new.autorizado_cliente then
    raise exception 'Se requiere registrar la aprobación del cliente.' using errcode='23514';
  end if;
  return new;
end; $$;
drop trigger if exists taller_validar_aprobacion on public.taller_ordenes;
create trigger taller_validar_aprobacion before update of estado on public.taller_ordenes
for each row execute function public.taller_validar_aprobacion_cliente();
revoke all on function public.taller_validar_aprobacion_cliente() from public, anon, authenticated;

do $$ declare t text; begin
  foreach t in array array['taller_repuestos','taller_orden_repuestos','taller_pagos','taller_comunicaciones'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_access', t);
    execute format('create policy %I on public.%I for all to authenticated using (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in (''admin'',''ventas''))) with check (exists(select 1 from public.perfiles p where p.id=auth.uid() and p.activo=true and p.rol in (''admin'',''ventas'')))', t || '_access', t);
  end loop;
end $$;
grant select, insert on public.taller_repuestos to authenticated;
grant select on public.taller_orden_repuestos to authenticated;
grant select, insert on public.taller_pagos, public.taller_comunicaciones to authenticated;
grant usage, select on sequence public.taller_repuestos_id_seq, public.taller_orden_repuestos_id_seq, public.taller_pagos_id_seq, public.taller_comunicaciones_id_seq to authenticated;

-- La salida de repuestos se realiza en una transacción y no permite existencias negativas.
create or replace function public.taller_agregar_repuesto(p_orden_id bigint, p_repuesto_id bigint, p_cantidad integer, p_usuario uuid)
returns void language plpgsql security definer set search_path=public as $$
declare r public.taller_repuestos%rowtype;
begin
  if p_usuario is distinct from auth.uid() or not exists(select 1 from public.perfiles where id=auth.uid() and activo=true and rol in ('admin','ventas')) then raise exception 'No tienes acceso al taller.' using errcode='42501'; end if;
  if p_cantidad is null or p_cantidad < 1 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
  select * into r from public.taller_repuestos where id=p_repuesto_id and activo=true for update;
  if not found then raise exception 'No se encontró el repuesto.'; end if;
  if r.existencias < p_cantidad then raise exception 'Existencias insuficientes.'; end if;
  update public.taller_repuestos set existencias=existencias-p_cantidad where id=p_repuesto_id;
  insert into public.taller_orden_repuestos(orden_id,repuesto_id,descripcion,cantidad,precio_unitario,creado_por)
    values(p_orden_id,p_repuesto_id,r.nombre,p_cantidad,r.precio,p_usuario);
end; $$;
revoke all on function public.taller_agregar_repuesto(bigint,bigint,integer,uuid) from public, anon;
grant execute on function public.taller_agregar_repuesto(bigint,bigint,integer,uuid) to authenticated;
create or replace function public.taller_reponer_repuesto(p_repuesto_id bigint, p_cantidad integer)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not exists(select 1 from public.perfiles where id=auth.uid() and activo=true and rol in ('admin','ventas')) then raise exception 'No tienes acceso al taller.' using errcode='42501'; end if;
  if p_cantidad is null or p_cantidad < 1 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
  update public.taller_repuestos set existencias=existencias+p_cantidad where id=p_repuesto_id and activo=true;
  if not found then raise exception 'No se encontró el repuesto.'; end if;
end; $$;
revoke all on function public.taller_reponer_repuesto(bigint,integer) from public, anon;
grant execute on function public.taller_reponer_repuesto(bigint,integer) to authenticated;
notify pgrst, 'reload schema';
commit;
