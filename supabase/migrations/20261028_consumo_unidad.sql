-- Permite registrar consumos de maestros en copias o quetzales.
-- El monto se conserva normalizado a quetzales para calcular el saldo.
alter table public.consumos
  add column if not exists unidad text not null default 'fotocopias';

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'consumos_unidad_check'
      and conrelid = 'public.consumos'::regclass
  ) then
    alter table public.consumos
      add constraint consumos_unidad_check
      check (unidad in ('fotocopias', 'quetzales'));
  end if;
end;
$$;

-- La vista del formato también presenta ajustes administrativos de saldo.
-- Esta definición hace que el script funcione aunque no se haya aplicado
-- previamente la migración que normalmente crea esta tabla.
create table if not exists public.ajustes_saldo (
  id bigint generated by default as identity primary key,
  maestro_id bigint not null references public.maestros(id),
  escuela_id bigint not null references public.escuelas(id),
  saldo_delta numeric(12,2) not null check (saldo_delta <> 0),
  motivo text not null,
  creado_por uuid references public.perfiles(id),
  creado_en timestamptz not null default now()
);

alter table public.ajustes_saldo enable row level security;
drop policy if exists ajustes_saldo_select on public.ajustes_saldo;
create policy ajustes_saldo_select on public.ajustes_saldo
  for select to authenticated
  using (public.es_admin() or escuela_id = public.mi_escuela());
grant select on public.ajustes_saldo to authenticated;
grant usage, select on sequence public.ajustes_saldo_id_seq to authenticated;

create or replace view public.saldo_maestro
with (security_invoker = true) as
select
  m.escuela_id,
  m.id as maestro_id,
  m.nombre as maestro,
  coalesce(a.asignado, 0)::numeric as asignado,
  coalesce(c.consumido, 0)::numeric as consumido,
  (coalesce(a.asignado, 0) + coalesce(j.ajustado, 0) - coalesce(c.consumido, 0))::numeric as saldo
from public.maestros m
left join (
  select maestro_id, sum(monto) as asignado
  from public.asignaciones where not anulada group by maestro_id
) a on a.maestro_id = m.id
left join (
  select maestro_id, sum(monto) as consumido
  from public.consumos where not anulado group by maestro_id
) c on c.maestro_id = m.id
left join (
  select maestro_id, sum(saldo_delta) as ajustado
  from public.ajustes_saldo group by maestro_id
) j on j.maestro_id = m.id
where m.activo;

grant select on public.saldo_maestro to authenticated;

create or replace view public.hoja_maestro_acumulada
with (security_invoker = true) as
with asignado as (
  select maestro_id, sum(monto) as monto
  from public.asignaciones where not anulada group by maestro_id
), movimientos as (
  select c.maestro_id, c.fecha, c.periodo, c.id, 1 as orden,
    'consumo'::text as tipo, c.catedratico::text as catedratico,
    c.descripcion::text as descripcion, c.monto::numeric(12,2) as importe,
    c.recibido_conforme, c.recibido_por::text as recibido_por,
    -c.monto::numeric(12,2) as cambio, c.unidad::text as unidad
  from public.consumos c where not c.anulado
  union all
  select j.maestro_id, j.creado_en::date,
    date_trunc('month', j.creado_en)::date, j.id, 0,
    'ajuste'::text, 'Administración'::text,
    ('Ajuste de saldo: ' || j.motivo)::text, j.saldo_delta::numeric(12,2),
    false, null::text, j.saldo_delta::numeric(12,2), 'fotocopias'::text
  from public.ajustes_saldo j
)
select x.maestro_id, x.fecha, x.periodo, x.tipo, x.catedratico,
  x.descripcion, x.importe, x.recibido_conforme, x.recibido_por,
  (coalesce(a.monto, 0) + sum(x.cambio) over (
    partition by x.maestro_id order by x.fecha, x.orden, x.id
    rows between unbounded preceding and current row
  ))::numeric(12,2) as saldo,
  x.unidad
from movimientos x
left join asignado a on a.maestro_id = x.maestro_id;

grant select on public.hoja_maestro_acumulada to authenticated;
notify pgrst, 'reload schema';
